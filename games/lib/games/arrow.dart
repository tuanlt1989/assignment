import 'dart:math';

import 'package:flutter/material.dart';

import 'session.dart';

enum Dir { up, down, left, right }

extension on Dir {
  (int, int) get delta => switch (this) {
    Dir.up => (-1, 0),
    Dir.down => (1, 0),
    Dir.left => (0, -1),
    Dir.right => (0, 1),
  };
  IconData get icon => switch (this) {
    Dir.up => Icons.arrow_upward_rounded,
    Dir.down => Icons.arrow_downward_rounded,
    Dir.left => Icons.arrow_back_rounded,
    Dir.right => Icons.arrow_forward_rounded,
  };
  Color get color => switch (this) {
    Dir.up => const Color(0xFF1E88E5),
    Dir.down => const Color(0xFFE53935),
    Dir.left => const Color(0xFF43A047),
    Dir.right => const Color(0xFFFB8C00),
  };
}

/// A board of arrows. Generated by inserting arrows whose path to the edge
/// is clear at insertion time, so removing them in reverse insertion order
/// always works: every level is solvable.
class ArrowBoard {
  ArrowBoard(this.size, this.arrows);
  final int size;

  /// Cell index (r * size + c) -> direction.
  final Map<int, Dir> arrows;

  bool canExit(int cell) {
    final dir = arrows[cell];
    if (dir == null) return false;
    final (dr, dc) = dir.delta;
    var r = cell ~/ size + dr;
    var c = cell % size + dc;
    while (r >= 0 && r < size && c >= 0 && c < size) {
      if (arrows.containsKey(r * size + c)) return false;
      r += dr;
      c += dc;
    }
    return true;
  }

  static ArrowBoard generate(int level, int seed) {
    final rnd = Random(seed);
    final size = (5 + level ~/ 6).clamp(5, 9);
    final fill = min(0.85, 0.55 + level * 0.01);
    final target = (size * size * fill).round();
    final board = ArrowBoard(size, {});
    var attempts = 0;
    while (board.arrows.length < target && attempts < 6000) {
      attempts++;
      final cell = rnd.nextInt(size * size);
      if (board.arrows.containsKey(cell)) continue;
      final dirs = Dir.values.toList()..shuffle(rnd);
      for (final d in dirs) {
        board.arrows[cell] = d;
        if (board.canExit(cell)) break;
        board.arrows.remove(cell);
      }
    }
    return board;
  }
}

class ArrowGame extends StatefulWidget {
  const ArrowGame({super.key, required this.session});
  final GameSession session;

  @override
  State<ArrowGame> createState() => _ArrowGameState();
}

class _ArrowGameState extends State<ArrowGame> {
  late final ArrowBoard _board = ArrowBoard.generate(
    widget.session.level,
    widget.session.seed,
  );
  final Set<int> _leaving = {};
  int? _blocked;
  int? _hinted;
  int _hearts = 3;
  bool _over = false;

  @override
  void initState() {
    super.initState();
    widget.session.hint.addListener(_showHint);
  }

  @override
  void dispose() {
    widget.session.hint.removeListener(_showHint);
    super.dispose();
  }

  void _showHint() {
    final free = _board.arrows.keys
        .where((c) => !_leaving.contains(c) && _board.canExit(c))
        .toList();
    if (free.isNotEmpty) setState(() => _hinted = free.first);
  }

  void _tap(int cell) {
    if (_over || _leaving.contains(cell) || !_board.arrows.containsKey(cell)) {
      return;
    }
    if (_board.canExit(cell)) {
      setState(() {
        _leaving.add(cell);
        if (_hinted == cell) _hinted = null;
      });
      Future.delayed(const Duration(milliseconds: 220), () {
        if (!mounted) return;
        setState(() {
          _board.arrows.remove(cell);
          _leaving.remove(cell);
        });
        if (_board.arrows.isEmpty && !_over) {
          _over = true;
          widget.session.onWin();
        }
      });
    } else {
      setState(() {
        _blocked = cell;
        _hearts--;
      });
      Future.delayed(const Duration(milliseconds: 350), () {
        if (mounted) setState(() => _blocked = null);
      });
      if (_hearts <= 0 && !_over) {
        _over = true;
        widget.session.onFail();
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final n = _board.size;
    return Column(
      children: [
        const SizedBox(height: 12),
        Hearts(left: _hearts),
        Expanded(
          child: Center(
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: AspectRatio(
                aspectRatio: 1,
                child: LayoutBuilder(
                  builder: (context, box) {
                    final cell = box.maxWidth / n;
                    return Stack(
                      children: [
                        for (final e in _board.arrows.entries)
                          _arrowTile(e.key, e.value, cell),
                      ],
                    );
                  },
                ),
              ),
            ),
          ),
        ),
      ],
    );
  }

  Widget _arrowTile(int index, Dir dir, double cell) {
    final n = _board.size;
    final leaving = _leaving.contains(index);
    final (dr, dc) = dir.delta;
    final blocked = _blocked == index;
    final hinted = _hinted == index;
    return AnimatedPositioned(
      key: ValueKey(index),
      duration: const Duration(milliseconds: 220),
      curve: Curves.easeIn,
      left: (index % n + (leaving ? dc * n : 0)) * cell,
      top: (index ~/ n + (leaving ? dr * n : 0)) * cell,
      width: cell,
      height: cell,
      child: GestureDetector(
        onTap: () => _tap(index),
        child: AnimatedContainer(
          duration: const Duration(milliseconds: 150),
          margin: EdgeInsets.all(cell * 0.06),
          decoration: BoxDecoration(
            color: blocked
                ? Colors.red.shade100
                : dir.color.withValues(alpha: 0.14),
            borderRadius: BorderRadius.circular(cell * 0.22),
            border: Border.all(
              color: hinted ? Colors.amber.shade600 : dir.color,
              width: hinted ? 4 : 2,
            ),
          ),
          child: Icon(dir.icon, color: dir.color, size: cell * 0.6),
        ),
      ),
    );
  }
}
