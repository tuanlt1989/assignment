// Release signing: android/key.properties (local) or the ANDROID_KEYSTORE_* env
// vars (CI). Without either, release builds fall back to the debug key, which
// is fine for testing but cannot be uploaded to Google Play.
val keystoreProperties = Properties().apply {
    val f = rootProject.file("key.properties")
    if (f.exists()) load(FileInputStream(f))
}
fun signingValue(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)

